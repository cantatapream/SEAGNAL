/**
 * ============================================================================
 * palette.js — KMA 해상 수치예보 유의파고 색상 → 등급(미터) 분류
 * ============================================================================
 *
 * 위험기상일기도(ReWW3/CoWW3) GIF 의 유의파고 음영은 0.5m 간격의 이산 팔레트다.
 * 범례(우측 색상 막대)의 표준 색을 기준 앵커로 두고, 임의 픽셀을 가장 가까운
 * 앵커로 분류한다. (샘플 차트에서 추출한 실측 RGB 로 보정)
 *
 * 핵심 임계:
 *   - 유의파고 ≥ 3.0m  → 풍랑주의보 기준
 *   - 유의파고 ≥ 5.0m  → 풍랑경보 기준
 *
 * 분류에서 제외(육지/배경/격자/글자/바람깃):
 *   - 무채색(회색·검정·흰색)  : 해안선·바람깃·풍속 라벨·격자
 *   - 크림색(육지)            : (255,255,229) 부근
 * ============================================================================
 */
'use strict';

// 범례 앵커: [유의파고 하한(m), R, G, B]
// 0.5m 간격. 샘플(kim_rww3_wave_ft03_pa4_) 실측 + KMA 표준 팔레트 기준.
const ANCHORS = [
    [0.0, 255, 255, 255],
    [0.5, 215, 235, 255],
    [1.0, 184, 218, 253],
    [1.5, 102, 166, 255],
    [2.0, 76, 140, 255],   // 진한 파랑 (≤2.0 = 안정)
    [2.0, 154, 255, 129],  // 초록 시작 (2.0~2.5 = 상승 조짐)
    [2.5, 103, 229, 78],
    [3.0, 255, 255, 0],    // 노랑 = 3.0m↑  ★ 풍랑주의보 임계
    [3.5, 255, 229, 80],
    [4.0, 255, 200, 120],
    [4.5, 255, 180, 120],  // 주황
    [5.0, 230, 100, 60],   // 빨강 = 5.0m↑  ★ 풍랑경보 임계
    [5.5, 153, 0, 0],      // 진한 빨강
    [6.0, 200, 40, 120],
    [7.0, 150, 0, 200],    // 보라
    // [주의] 범례 최상단 7.5~10m 는 '진초록' 계열이지만, 이 색은 차트에 그려진
    //   '특보구역 경계선(진초록 폴리곤)' 과 충돌한다. 한국 연안 유의파고가 7.5m 를
    //   넘는 경우는 극한 태풍뿐이고, 그 경우에도 주변에 5~7m(빨강·보라)가 동반되므로
    //   풍랑(3m/5m) 분석에는 진초록 앵커를 두지 않는다 → 경계선이 wave 로 오분류되는
    //   false positive 제거. (genuine ≥7.5m 는 동반 빨강/보라로 ≥5m 판정에 이미 잡힘)
];

const LAND_RGB = [255, 255, 229];

function isGray(r, g, b) {
    return Math.max(r, g, b) - Math.min(r, g, b) < 22;
}
function isLand(r, g, b) {
    return Math.abs(r - LAND_RGB[0]) < 16 && Math.abs(g - LAND_RGB[1]) < 16 && Math.abs(b - LAND_RGB[2]) < 16;
}

/**
 * 픽셀 → 유의파고 등급(m). 분류 대상 아니면 null.
 * @returns {number|null} 해당 픽셀의 유의파고 하한(m), 또는 null(육지/무채색)
 */
function classify(r, g, b) {
    if (isLand(r, g, b)) return null;
    if (isGray(r, g, b)) return null;
    let best = null, bestD = Infinity;
    for (const [m, ar, ag, ab] of ANCHORS) {
        const d = (r - ar) ** 2 + (g - ag) ** 2 + (b - ab) ** 2;
        if (d < bestD) { bestD = d; best = m; }
    }
    // 너무 먼 색(앵커와 거리가 큼)은 노이즈로 간주해 제외
    if (bestD > 9000) return null;
    return best;
}

module.exports = { classify, isGray, isLand, ANCHORS };
