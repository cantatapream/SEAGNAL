// 3-64 — 가리킴 앞의 **계층어**를 읽어 그 계층의 별표로 보낸다 (그리고 **안 보낼 것은 안 보낸다**)
//
// [왜 이 스위트가 있나] 고시가 `영 별표 제1호`(= 상위법 시행령의 별표1)라 써도 종전에는
//   `{key:'별표1'}` 만 돌려줘 **그 고시의 별표1** 을 찾다 못 찾고 「(원문 미수집)」으로 보였다.
//   그 파일은 **같은 법 폴더에 있었다**(`<법>/별표/시행령_별표1.txt`) — 못 찾은 게 아니라
//   **엉뚱한 이름으로 찾고 있었다**(`TIER_BYL_PREFIX` 에 notice 가 없어 그 단계가 통째로 안 돌았다).
//
// [★이 자리가 위험하다] `byl_ref_gap.py` 가 **바로 여기서 여섯 번** 틀렸다 — 걸러 내려다
//   분모가 563→172 로 주저앉았다. **과교정은 미교정보다 나쁘다.** 그래서 이 스위트는
//   「보내는 것」보다 **「안 보내는 것」을 더 많이** 못박는다. 고정 문장은 전부 실물 raw 에서 왔다.
//
// [무엇이 규칙인가]
//   ① 계층어가 **낱말 경계 뒤에 홀로** 서 있어야 한다 — `해사안전법 별표` 의 `법` 은 낱말의 꼬리다.
//   ② 앞에 **남의 법 이름**(`「…법」`·`…법률」`)이나 **「같은 …」**이 있으면 안 받는다.
//      「같은 법」은 앞 문장이 가리키는 법이라 상위법일 수도 남의 법일 수도 있다(표본에 둘 다 있다).
//   ③ 한 문서가 `영 별표 1` 과 `별표 1` 을 **둘 다** 쓰는 경우가 실측 96파일·151열쇠 있다 —
//      그래서 중복 제거를 `열쇠|계층` 으로 한다. 열쇠 꼴 자체는 **안 바꾼다**(화면·게이트가 읽는다).
const at = require('../services/article_text.js');

let pass = 0, fail = 0;
const ok = (name, cond, detail) => {
  if (cond) { pass++; console.log('  ✅ ' + name); }
  else { fail++; console.log('  ❌ ' + name + (detail ? ' — ' + detail : '')); }
};
const tierOf = (text) => {
  const rs = at.collectRefs(text);
  return (rs[rs.length - 1] || {}).tier || null;
};

console.log('── 보낸다 (맨몸 계층어 — 이 고시의 상위법 계층) ──');
[
  ['제3조 … 표지의 크기와 형상은 시행규칙 별표 1 에 따른다.', 'rule'],
  ['② (해양공간적합성협의 대상의 범위) 시행령 별표 1', 'decree'],
  ['해저자원 개발에 관한 계획) : 영 별표 제2 와 같다.', 'decree'],
  ['해양조사기술자는 영 별표 2 의 교육을 받는다.', 'decree'],
  ['1. 일반수로측량 신고서(규칙 별지 제6호서식)', 'rule'],
  ['④ 구급요원의 업무범위는 시행규칙 별표 14 와 같다.', 'rule'],
].forEach(([t, want]) => ok(`${want} — ${t.slice(0, 34)}`, tierOf(t) === want, String(tierOf(t))));

console.log('── 안 보낸다 (남의 법·「같은 법」·낱말 꼬리) ──');
[
  ['「화학물질관리법」 시행규칙 별표1 에 따른다.', '남의 법(따옴표)'],
  ['「군사기지 및 군사시설보호법」시행령 별표 1', '남의 법(따옴표·붙여쓰기)'],
  ['소방시설 설치유지에 관한 법률」 시행규칙 별표 2의2', '남의 법(닫는 따옴표만 남음)'],
  ['제2조(대상물질) 「물환경보전법」 시행규칙 별표3', '남의 법'],
  ['법 제42조 및 같은 법 시행규칙 별지 제37호서식', '「같은 법」 — 가릴 수 없다'],
  ['별표 10의2에 따른 비산배출시설, 같은 법 별표 13', '「같은 법」'],
  ['해사안전법 별표 2 에 따른다.', '낱말의 꼬리 — 법 이름의 일부'],
  ['해양환경관리법 시행령 별표 1', '법 이름이 계층어를 데리고 있다'],
  ['검사수수료는 별표 1과 같다.', '계층어가 없다(지금까지와 같다)'],
  ['… 별지 제1호서식에 따라 신청한다.', '계층어가 없다'],
].forEach(([t, why]) => ok(`안 보낸다(${why}) — ${t.slice(0, 30)}`, tierOf(t) === null, String(tierOf(t))));

console.log('── 열쇠 꼴은 안 바뀐다 · 계층은 덤으로만 붙는다 ──');
{
  const plain = at.collectRefs('검사수수료는 별표 1과 같다.');
  ok('계층이 없으면 tier 필드 자체가 없다(종전과 똑같다)',
    plain.length === 1 && plain[0].key === '별표1' && !('tier' in plain[0]), JSON.stringify(plain[0]));
  const tiered = at.collectRefs('그 기준은 시행령 별표 1 에 따른다.');
  ok('계층이 있어도 key 는 그대로 `별표1`', tiered[0].key === '별표1', JSON.stringify(tiered[0]));
  ok('계층은 tier 필드로만 붙는다', tiered[0].tier === 'decree', JSON.stringify(tiered[0]));
}

console.log('── 한 문서가 둘 다 쓰면 갈라서 남긴다 (실측 96파일·151열쇠) ──');
{
  const both = at.collectRefs('수수료는 별표 1과 같다. 다만 그 기준은 시행령 별표 1 에 따른다.');
  ok('같은 번호라도 맨몸과 계층붙은 것이 **따로** 남는다', both.length === 2, JSON.stringify(both));
  ok('둘의 key 는 같고 tier 로 갈린다',
    both.length === 2 && both[0].key === both[1].key
    && !both[0].tier && both[1].tier === 'decree', JSON.stringify(both));
  const twice = at.collectRefs('별표 1과 같다. 또 별표 1을 본다.');
  ok('똑같은 것이 두 번 나오면 여전히 하나로 줄인다', twice.length === 1, JSON.stringify(twice));
}

console.log('');
console.log(`${pass} PASS / ${fail} FAIL`);
process.exit(fail ? 1 : 0);
