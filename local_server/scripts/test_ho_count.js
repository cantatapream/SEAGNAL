#!/usr/bin/env node
/**
 * §5-D ⓕ 「각 호 N개」 세는 법을 못박는다 (2026-09-23, G-7)
 *
 * ★이 시험의 뼈대는 **규약이 직접 준 것**이다 — §5-D ⓕ 가 *"확인한 실례(둘 다 raw 원문을
 *   직접 열어 확인)"* 로 두 조를 적어 두었다. 규약이 자기 시험을 들고 온 셈이다.
 * ⚠L-136 — 세는 법을 여기서 다시 적지 않는다. `_counting.countHo` 를 부른다.
 */
const C = require('../knowledge/legal/_dashboard/loop/_counting.js');
const G = require('../knowledge/legal/_dashboard/loop/ho_count_gate.js');

let pass = 0, fail = 0;
const ok = (n, c, w) => { if (c) { pass++; console.log('  ✅ ' + n); } else { fail++; console.log('  ❌ ' + n); if (w) console.log(w); } };

// ── ① 규약이 준 실례 둘 ──────────────────────────────────────────────────────
const f1 = C.HO_FIXTURES[0];
const g1 = C.countHo(C.articleBlock(f1.파일, f1.조));
const h1 = g1.find((x) => x.항 === f1.항);
ok('§5-D ⓕ 실례① 선박직원법 제9조① — 살아 있는 호 7개', h1 && h1.살아있는 === 7,
    `        실제 ${h1 && h1.살아있는} — 규약: "${f1.근거}"`);
ok('§5-D ⓕ 실례① — 마지막 번호는 8 (개수 7과 다르다)', h1 && h1.마지막번호 === '8',
    `        실제 ${h1 && h1.마지막번호}\n        ★이 둘이 같아지면 「삭제된 호」를 세고 있다는 뜻이다.`);
ok('§5-D ⓕ 실례① — 삭제된 호 1개를 따로 센다', h1 && h1.삭제 === 1);

const f2 = C.HO_FIXTURES[1];
const g2 = C.countHo(C.articleBlock(f2.파일, f2.조));
ok('§5-D ⓕ 실례② 선박직원법 시행령 제2조 — 가지번호 2의2·2의3 을 잡는다',
    g2[0] && JSON.stringify(g2[0].가지번호) === JSON.stringify(['2의2', '2의3']),
    `        실제 ${JSON.stringify(g2[0] && g2[0].가지번호)}`);
ok('§5-D ⓕ 실례② — 가지번호를 **한 개씩** 센다(건너뛰지 않는다)',
    g2[0] && g2[0].번호들.includes('2의2') && g2[0].번호들.includes('2의3'));

// ── ② 규칙 자체 ──────────────────────────────────────────────────────────────
const SAMPLE = [
    '① 다음 각 호와 같다.',
    '   1.  가',
    '   2.  나',
    '   2의2.  다',
    '   3.  삭제 <2020.2.18>',
    '   4.  라',
    '      가.  목은 호가 아니다',
    '      나.  이것도 아니다',
].join('\n');
const s = C.countHo(SAMPLE)[0];
ok('삭제된 호는 안 센다', s.살아있는 === 4 && s.삭제 === 1, `        살아있는 ${s.살아있는} · 삭제 ${s.삭제} · 번호들 ${JSON.stringify(s.번호들)}`);
// ⚠이 시험은 처음에 `/[가-힣]/` 로 「한글이 섞였나」를 봤다가 **스스로 틀렸다** —
//   가지번호 `2의2` 의 `의` 가 한글이라 걸렸다. 자가 아니라 **내 시험이 틀린 것**이었다.
//   목은 **한글로 시작**하므로 시작 글자만 본다.
ok('★목(가.·나.)은 호가 아니다', !s.번호들.some((n) => /^[가-힣]/.test(n)) && s.살아있는 === 4,
    `        번호들 ${JSON.stringify(s.번호들)} — 목이 섞이면 개수가 부풀려진다`);
ok('마지막 번호(4)와 개수(4)가 우연히 같아도 삭제는 따로 남는다', s.마지막번호 === '4' && s.삭제 === 1);

// ── ③ 게이트가 사전을 부른다 · 지금 어긋남 0 ────────────────────────────────
const r = G.check();
ok('게이트가 위키 주장을 실제로 찾아낸다(0건이면 아무것도 안 재는 것이다)', r.주장 > 0,
    `        주장 ${r.주장}건`);
ok('★지금 위키에 원문과 어긋난 「각 호 N개」 는 없다', r.어긋남.length === 0,
    '        ' + r.어긋남.map((b) => `${b.page} ${b.jo} 위키 ${b.위키} ↔ 원문 ${b.원문}`).join('\n        '));
ok('닿지 못한 주장 수를 숨기지 않고 돌려준다', typeof r.못맞춤 === 'number');

console.log(`\n${pass} PASS / ${fail} FAIL`);
process.exit(fail ? 1 : 0);
