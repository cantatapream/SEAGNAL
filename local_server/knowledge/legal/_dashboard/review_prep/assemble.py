srcs += [(n, os.path.join(HERE, f'prep{n}.json')) for n in range(8)]
for n, p in srcs:
    if not os.path.exists(p):
        missing.append(n); continue
    for it in json.load(open(p)):
        rid = it.get('id', '')
        # 묶음5 에이전트가 자기 중복방지용으로 넣은 더미('-dup' 접미사)는 실제 큐 항목이 아니다.
        if rid.endswith('-dup') or rid.endswith('-dup2'):
            dropped_dummy += 1; continue
        if rid in seen:
            continue
        seen.add(rid)
        it['_batch'] = n
        it['_kind'] = norm(it.get('kind'))
        items.append(it)

# 큐 자체에 같은 ID가 두 번 등록된 것 — 사람이 두 번 누르게 되는 항목이라 따로 알린다.
qdup = []
for n in range(8):
    bp = os.path.join(HERE, f'batch{n}.json')
    if not os.path.exists(bp): continue
    for it in json.load(open(bp)):
        qdup.append(it['id'] if isinstance(it, dict) else it)
qdup = sorted(k for k, v in collections.Counter(qdup).items() if v > 1)

