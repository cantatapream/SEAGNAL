def norm(k):
    """'사실확인'과 '사실확인형'처럼 에이전트마다 다르게 쓴 갈래 이름을 하나로 맞춘다."""
    k = (k or '').strip()
    for base in ('사실확인', '방침결정', '수집공백'):
        if k.startswith(base):
            return base + '형'
    return '분류없음'

