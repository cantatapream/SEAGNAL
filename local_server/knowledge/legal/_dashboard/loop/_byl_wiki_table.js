/**
 * _byl_wiki_table.js — ★별표 위키 문서에서 **별표 표만** 골라내는 단 한 곳. (2026-09-27)
 *
 * [왜 있나 — 사장님께 검토장을 내밀기 전에 실측으로 잡았다]
 *   `annex_rowcount_fill.js` 와 `build_rowcount_html.js` 가 **각자** 위키 표를 세고 있었고,
 *   둘 다 **파일의 표를 전부** 긁었다. 위키 별표 문서에는 별표 표 말고도
 *   `## 근거 조문` · `## 변경 이력` 표가 있어서, 보기 —
 *     국제항해선박 시행규칙 별표2:
 *        별표 표 (머리1+데이터4=5) + 근거 조문 (1+4=5) + 변경 이력 (1+1=2) = **12**
 *        ← 위키 38쪽에 `기계 셈 12행` 으로 적힌 수가 이것이다
 *        별표 표만 데이터 줄로 세면 **4** (원문 4행과 같다)
 *   38쪽 전수로 재니 적힌 값과 바른 값이 같은 것은 **0/38** 이었다.
 *   그리고 검토장은 표를 3덩이씩 보여 주어 **어느 것을 세라는지 알 수 없는 물음**이 됐다.
 *   ⇒ 세는 법을 한 곳에 두고 둘이 같이 쓴다(L-386 · 같은 규칙이 두 곳에 있으면 한 곳만 고쳐진다).
 *
 * [연계] ← `wiki/annexes/*.md` · → `annex_rowcount_fill.js` · `build_rowcount_html.js`
 *         자매: 원문 쪽을 세는 자는 `article_text.countBoxRows`(운영 코드 · L-136)
 */

// ★별표가 **아닌** 표가 실려 있는 마디들. 머리글로 가른다(위키 38쪽을 훑어 모은 목록이다).
//   ⚠막는 쪽으로만 쓴다 — 허용 목록이 아니다. 새 마디가 생겨도 별표 표를 잃지 않는다.
const 딴마디 = /^(출처|근거\s*조문|변경\s*이력|관련|바뀐\s*자리|참고|링크|메모|덧댄\s*기록)/;

/**
 * 위키 문서에서 **별표 표만** 오려 낸다.
 * @param {string} text - 위키 `.md` 전문
 * @returns {{머리글:string, 글:string, 데이터행:number}[]}
 */
function 별표표(text) {
    const out = [];
    let 머리 = '(머리글 없음)';
    let cur = [];
    const 닫기 = () => {
        if (cur.length >= 2) {
            // 맨 위 이름줄 1개와 `|---|---|` 구분줄은 항목이 아니다.
            const 데이터 = cur.filter((s) => !/^\|[\s:|-]+\|$/.test(s)).slice(1);
            out.push({ 머리글: 머리, 글: cur.join('\n'), 데이터행: 데이터.length });
        }
        cur = [];
    };
    for (const l of String(text || '').split('\n')) {
        if (/^#+\s/.test(l)) { 닫기(); 머리 = l.replace(/^#+\s*/, '').trim(); continue; }
        if (l.trim().startsWith('|')) { cur.push(l.trim()); continue; }
        닫기();
    }
    닫기();
    return out.filter((x) => !딴마디.test(x.머리글));
}

/** 그 위키 문서의 **별표 표 데이터 줄 합**. 표가 없으면 0. */
function 별표행수(text) {
    return 별표표(text).reduce((a, x) => a + x.데이터행, 0);
}

/**
 * 그 위키 문서가 별표 본문을 **`###` 마디로 풀어 놓았나.** → 마디 개수
 * ⚠이런 쪽은 「표가 몇 행이냐」로 견줄 수 없다 — 표 한 줄이 한 항목이 아니기 때문이다.
 *   보기: 수산업법 시행령 별표2 는 원문 154행을 **어업 40종의 `###` 마디**로 풀어 835줄에 담았다.
 *   행으로 견주면 「154 대 18」이 되어 큰 누락처럼 보이지만, 실측하니 **빠진 것이 없었다**
 *   (원문에 나오는 「…어업」 46가지가 위키에 모두 있고, 문서가 주장한 원문 20,099자도 정확했다).
 * `## 근거 조문` 뒤(꼬리표 마디)는 세지 않는다 — 본문이 아니다.
 */
function 마디수(text) {
    const 본문 = String(text || '').split(/\n##\s*(?:근거\s*조문|출처|변경\s*이력)/)[0];
    return (본문.match(/^###\s/gm) || []).length;
}

/**
 * 원문 별표의 **큰 마디 이름**(`  1. 무엇` 꼴). 마디로 풀어 놓은 쪽을 견주는 자.
 * ⚠**괄호 꼬리를 뗀다.** 처음에는 줄을 통째로 넣고 위키에서 글자 그대로 찾았는데,
 *   `1. 투망(영 제7조의2제1항제1호가목)` 처럼 조문 인용이 붙어 있어 위키의 「투망」과 안 맞았다.
 *   그 탓에 수산자원관리법 별표1 에서 **거짓 「6가지 다 없다」**가 났다(2026-09-27, 내밀기 전에 잡았다).
 *   ⇒ 괄호·대괄호 안을 떼고 **이름만** 남겨 견준다.
 */
function 원문큰마디(text) {
    const out = [];
    for (const l of String(text || '').split('\n')) {
        const m = l.match(/^\s{0,4}(\d{1,2})\.\s+(\S.{2,80}?)\s*$/);
        if (!m || /[│┃|]/.test(l)) continue;
        const 이름 = m[2]
            .replace(/[\(\[][^)\]]*[\)\]]/g, ' ')   // `(영 제7조의2…)` · `[영 …]` 를 뗀다
            .replace(/\s+/g, ' ')
            .trim();
        if (이름.length >= 2) out.push(이름);
    }
    return [...new Set(out)];
}

/**
 * 원문 큰마디 이름이 위키에 있나. → 없는 것들
 * 이름이 `가, 나, 다` 처럼 쉼표로 여럿이면 **하나라도 있으면 있는 것**으로 본다
 * (위키가 그 여럿을 따로 마디로 쪼개 적기 때문이다).
 */
function 없는큰마디(raw, wiki) {
    const w = String(wiki || '');
    return 원문큰마디(raw).filter((이름) => {
        const 쪽들 = 이름.split(/[,、·ㆍ]/).map((x) => x.trim()).filter((x) => x.length >= 2);
        const 볼것 = 쪽들.length ? 쪽들 : [이름];
        return !볼것.some((x) => w.includes(x));
    });
}

module.exports = { 별표표, 별표행수, 마디수, 원문큰마디, 없는큰마디, 딴마디 };
