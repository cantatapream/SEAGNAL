RE_ART = re.compile(r'^\[제(\d+)조(?:의(\d+))?\]\s*(.*)$')
RE_ART_NB = re.compile(r'^제(\d+)조(?:의(\d+))?\s*\(([^)]*)\)')   # 고시계열(L-54)
RE_BYL_NB = re.compile(r'\[별표\s?(\d+)\]\s*$')                    # 고시계열 별표 머리(줄 끝에 있을 때만)


def load_laws():
    """74법 목록 = audit12_groups.json(73) ∪ audit12_groups_run.json에만 있는 1법(자연유산법).
    근거: _dashboard/H29_design.md §2 (같은 목록을 H-29·서류 트리가 이미 채택)."""
    def flat(p):
        g = json.load(open(p, encoding='utf-8'))
        return [it for k in sorted(g, key=int) for it in g[k]]
    base = flat(os.path.join(HERE, 'audit12_groups.json'))
    run = flat(os.path.join(HERE, 'audit12_groups_run.json'))
    slugs = {x['slug'] for x in base}
    return base + [x for x in run if x['slug'] not in slugs]


LAWS = load_laws()
BY_SLUG = {x['slug']: x for x in LAWS}


def split_articles(text):
    """법률계열 raw(`[제10조] 제목 …`)를 조 단위로 쪼갠다."""
    out, cur, buf = {}, None, []
    for line in text.split('\n'):
        m = RE_ART.match(line.strip())
        if m:
            if cur:
                out[cur] = '\n'.join(buf)
            cur = '제%s조' % m.group(1) + ('의%s' % m.group(2) if m.group(2) else '')
            buf = [line.strip()]
        else:
            if cur is not None:
                buf.append(line)
    if cur:
        out[cur] = '\n'.join(buf)
    return out


_cache = {}


def article_body(slug, tier, article):
    """(법, 계층, 조) → 그 조의 raw 원문 전체. 없으면 None."""
    key = (slug, tier)
    if key not in _cache:
        law = BY_SLUG.get(slug)
        if not law:
            _cache[key] = {}
        else:
            p = os.path.join(law['raw'], TIER_FILE[tier])
            _cache[key] = split_articles(open(p, encoding='utf-8', errors='replace').read()) \
                if os.path.exists(p) else {}
    return _cache[key].get(article)


def law_id(slug, tier):
    """_meta.json의 families.<계층>.법령ID — 법령명이 바뀌어도 추적이 끊기지 않게(H-29 11항·L-74)."""
    law = BY_SLUG.get(slug)
    if not law:
        return None
    p = os.path.join(law['raw'], '_meta.json')
    if not os.path.exists(p):
        return None
    fam = json.load(open(p, encoding='utf-8')).get('families', {})
    f = fam.get(tier)
    if isinstance(f, list):
        f = f[0] if f else None
    return (f or {}).get('법령ID')


def rel(slug, tier):
    return os.path.relpath(os.path.join(BY_SLUG[slug]['raw'], TIER_FILE[tier]), LEGAL)


IMG_RE = re.compile(r'<img[^>]*>|</img>')


def flatten(body):
    """조문 원문을 한 줄로 편다. 이미지 태그(<img …>船?</img>)만 지운다 —
    raw에 그림으로 들어간 한자가 태그째 인용문에 섞이면 읽을 수 없기 때문이다."""
    return re.sub(r'\s+', ' ', IMG_RE.sub(' ', body)).strip()


HANG_RE = re.compile(r'[①-⑳]')                      # 항 표시
HO_RE = re.compile(r'(?<![\d.])(\d{1,2}(?:의\d+)?)\. ')  # 호 표시("1. ", "3의2. ") — 날짜(2013.3.23)는 걸리지 않음
MOK_RE = re.compile(r'(?:^| )([가-하])\. ')            # 목 표시("가. ", "나. ")
CLEAN_START_RE = re.compile(r'^(\[제|[①-⑳]|\d{1,2}(?:의\d+)?\. |[가-하]\. |"|「)')


def with_proviso(q, flat, end, cap=400):
    """인용문 `q` 바로 뒤에 "다만 …" 단서가 붙어 있으면 그 단서 한 문장을 함께 싣는다.

    본문 끝점 계산이 "다. "에서 끊기 때문에 "…하여야 한다." 다음에 오는 단서("다만, 허가를 받은
    경우에는 그러하지 아니하다")가 절단표시도 없이 사라진다 — 화면에는 예외 없는 규정으로 보여
    **원문보다 엄격해진다**(적대검증 §5-A, 실제 7건). 단서의 끝은 본문과 같은 규칙(다음 항·호 표시
    또는 첫 "다. ")으로 잡고, 상한(cap)을 넘으면 그때만 잘라내되 말줄임표를 반드시 남긴다.
    @param q 이미 뽑아낸 본문 인용문 @param flat 조문 전체(한 줄로 편 것) @param end 본문 끝 인덱스
    @returns {str} 단서를 이어붙인 인용문(단서가 없으면 q 그대로)
    """
    tail = flat[end:]
    if not tail.lstrip().startswith('다만'):
        return q
    p = end + (len(tail) - len(tail.lstrip()))
    pends = [p + 300, len(flat)]
    m = HANG_RE.search(flat, p + 2)
    if m:
        pends.append(m.start())
    m = HO_RE.search(flat, p + 2)
    if m:
        pends.append(m.start())
    k = flat.find('다. ', p + 2)
    if k > 0:
        pends.append(k + 2)
    clause = re.sub(r'\s(?:[가-하]|\d{1,2}(?:의\d+)?)\.$', '', flat[p:min(pends)].strip()).strip()
    if not clause:
        return q
    if len(q) + 1 + len(clause) <= cap:
        return q + ' ' + clause
    room = cap - len(q) - 2
    return (q + ' ' + clause[:room].rstrip() + '…') if room > 10 else (q + ' 다만, …')


def quote_of(body, anchor, span=320, wide=False, mark_cut=False, cap=400):
    """anchor를 포함한 대목을 원문에서 그대로 잘라 인용문으로 쓴다(사람이 타이핑하지 않는다).

    시작점 = 앵커 앞에서 가장 가까운 항(①…)·호("1. ") 표시 또는 문장 경계,
    끝점   = 앵커 뒤 첫 "다. " 또는 다음 호 표시, 그 전에 span 글자 상한.
    ★서류 트리(build_vessel_doc_tree.py)의 같은 함수는 항 표시만 보고 호 목록을 못 끊어,
      앵커가 인용문 밖으로 밀려나도 조용히 통과했다(이번 초안에서 실제로 재현). 그래서
      **뽑아낸 인용문 안에 앵커가 실제로 들어 있는지 마지막에 확인**하고, 없으면 None을 돌려
      빌드를 실패시킨다.
    ★"다만" 단서는 반드시 함께 싣는다(적대검증 §5-A). 본문 끝점이 마침 "…한다." 라서 바로 뒤에
      붙은 "다만, …인 경우에는 그러하지 아니하다"가 통째로 잘려나가면, 화면에는 큰따옴표로 감싼
      "원문"이 **예외 없는 규정**으로 보인다 — 원문보다 엄격해지는 쪽이라 위험하다(예: 영해및접속
      수역법 제5조제2항은 허가받은 조사·측량을 단서로 빼주는데, 같은 리프에 처벌 항목이 나란히 뜬다).
      단서까지 넣으면 상한(400자)을 넘는 경우에만 잘라내고, 그때는 반드시 말줄임표를 남긴다.
    @returns {str|None} 앵커를 담은 인용문. 범위 계산이 실패하면 None.
    """
    flat = flatten(body)
    i = flat.find(anchor)
    if i < 0:
        return None
    marks = [m.start() for m in HANG_RE.finditer(flat[:i])]
    marks += [m.start() for m in HO_RE.finditer(flat[:i])]
    marks += [m.start(1) for m in MOK_RE.finditer(flat[:i])]
    mark = max(marks) if marks else None
    sent = flat.rfind('. ', 0, i)
    sent = sent + 2 if sent >= 0 else None
    # 호·목 표시("1. ")는 그 자체가 마침표를 가지므로 문장경계 후보와 몇 글자 차이로 겹친다.
    # 그 경우엔 표시 쪽을 시작점으로 삼아 "1. …"처럼 번호부터 인용되게 한다.
    if mark is not None and (sent is None or sent - mark <= 6):
        start = mark
    else:
        start = max([x for x in (mark, sent) if x is not None], default=0)
    after = i + len(anchor)
    ends = [i + span]
    m = HANG_RE.search(flat, after)        # 다음 항으로 넘어가면 자른다
    if m:
        ends.append(m.start())
    if not wide:
        # wide=True 는 "각 호를 열거하는 것 자체가 내용"인 조문(적용범위 등)에서 쓴다 —
        # 첫 "다. "나 다음 호에서 자르면 정작 열거가 통째로 빠진다.
        k = flat.find('다. ', max(0, after - 1))
        if k > 0:
            ends.append(k + 2)
        m = HO_RE.search(flat, after)
        if m:
            ends.append(m.start())
    end = min(ends)
    cut = flat[start:end].strip()
    q = cut[:cap]
    # 끝에 매달린 다음 호·목 표시("… 세일링요트 다.")만 떼어낸다.
    # ⚠ 앞의 공백을 반드시 요구한다 — 없으면 "…적용한다."의 "다."까지 잘라 문장을 망가뜨린다(실측).
    #   ⚠단, **조문이 거기서 끝나는 경우(end == len(flat))에는 떼어내지 않는다** — PDF에서 뽑은
    #     고시 raw는 낱말이 줄바꿈으로 갈려("…것이어야 한\n다.") 공백 접기 후 "한 다."가 되는데,
    #     그걸 목 마커로 오인해 마지막 낱말을 깨뜨린 사례가 있다(선박방화구조기준 제28조제3항).
    #     뒤에 다른 항·호가 이어질 때만(end < len(flat)) 매달린 마커일 수 있다.
    if end < len(flat):
        q = re.sub(r'\s(?:[가-하]|\d{1,2}(?:의\d+)?)\.$', '', q).strip()
    # ★공백 없이 바로 붙은 호·목 표시도 떼어낸다(2026-08-11 고시 확장 중 실측).
    #   raw가 "…여객선을 제외한다.다. 호소, 하천…"처럼 마침표 뒤에 공백 없이 다음 목을 이어 쓰는
    #   경우가 있어, 위 규칙(앞 공백 필수)으로는 "제외한다.다."의 끝 "다."가 남아 문장이 망가진다.
    #   "…한다." 뒤에 마커 한 글자만 매달린 경우로 한정해 오작동 여지를 줄인다.
    q = re.sub(r'(?<=다\.)(?:[가-하]|\d{1,2}(?:의\d+)?)\.$', '', q).strip()
    # ★끝이 열린 개정이력 태그로 끝나면 떼어낸다("… 하는 선박 <개정 2007." 같은 조각).
    #   닫는 `>`가 있는 온전한 태그는 `[^>]*$`가 매치되지 않아 그대로 남는다.
    q = re.sub(r'\s*<(?:개정|신설|삭제|전문개정)[^>]*$', '', q).strip()
    if q == cut:                 # 끝을 이미 잘라낸 경우가 아닐 때만 단서를 이어붙인다
        q = with_proviso(q, flat, end, cap=cap)
        # 단서를 이어붙일 때도 열린 개정이력 태그가 딸려올 수 있다(실측: 선박설비기준 제44조).
        q = re.sub(r'\s*<(?:개정|신설|삭제|전문개정)[^>]*$', '', q).strip()
    # ★끝이 상한(span·400자)에 걸려 잘렸으면 그 사실을 드러낸다(2026-08-11).
    #   지금까지는 **시작점이 잘렸을 때만** 말줄임표를 붙였기 때문에, 표 한가운데나 낱말 중간에서
    #   끊긴 인용문이 온전한 문장처럼 보였다(설계 §6 초판이 시작점에 대해 잡았던 것과 같은 결함의
    #   반대쪽). 조문 끝에서 자연히 끝난 경우(end == len(flat))에는 붙이지 않는다.
    #   ⚠`mark_cut`은 이번(2026-08-11) 고시 확장에서 만든 항목에만 켠다. 기존 법률계열 79건에
    #     같은 규칙을 적용하면 인용문이 1건 바뀌어(선박안전법 시행령 제2조 평수구역 항목) 이번
    #     확장의 회귀검증("기존 항목 불변") 조건을 깨기 때문이다. 그 1건은 실제로 표시 없이 잘려
    #     있으므로 설계문서에 다음 라운드 과제로 남긴다 — 조용히 덮지 않는다.
    if mark_cut and (len(cut) > cap or (end == i + span and end < len(flat))) \
            and not q.endswith('…'):
        q = q + ' …'
    if anchor not in q:
        return None
    # 문장 중간에서 잘려 시작하면 그 사실을 말줄임표로 드러낸다(잘린 것을 온전한 문장처럼 보이지 않게).
    return q if CLEAN_START_RE.match(q) else '… ' + q


