def walk(n):
    yield n
    for c in n.get('children', []):
        yield from walk(c)


def validate(trees):
    """설계 §6 검증 — provenance 존재, payload 무결성, 질문·선택지 무결성, id 유일성."""
    seen_ids = set()
    for t in trees:
        nodes = list(walk(t['tree']))
        ids = {n['id'] for n in nodes}
        titles = {r['제목'] for n in nodes for r in n.get('적용', []) if r}
        has_rank = t['id'] == 'navigation_zone'
        for n in nodes:
            if n['id'] in seen_ids:
                ERRORS.append('id 중복: %s' % n['id'])
            seen_ids.add(n['id'])
            if not n.get('provenance') or any(p is None for p in n['provenance']):
                ERRORS.append('provenance 없음/실패: %s' % n['id'])
            if any(r is None for r in n.get('적용', [])):
                ERRORS.append('적용 항목 빌드 실패 포함: %s' % n['id'])
            for r in n.get('적용', []):
                if r and r['구역범위'] != '이 구역만' and not has_rank:
                    ERRORS.append('서열 없는 트리에서 구역범위 사용: %s ← %s' % (n['id'], r['제목']))
            if has_rank and n['id'] != t['tree']['id'] and '서열' not in n:
                ERRORS.append('항해구역 트리 노드에 서열 없음: %s' % n['id'])
            for ax in n.get('추가확인', []):
                if not ax.get('질문') or not ax.get('선택지'):
                    ERRORS.append('추가확인에 질문/선택지 없음: %s / %s' % (n['id'], ax.get('축')))
                for title in ax.get('영향', []):
                    if title not in titles:
                        # 잔여 축의 `영향`은 같은 트리 안에 실재하는 적용항목만 가리켜야 한다
                        # (깨진 `next` 참조와 같은 성격의 환각 통로다).
                        ERRORS.append('추가확인 영향이 실재하지 않는 항목을 가리킴: %s / %s ← "%s"'
                                      % (n['id'], ax.get('축'), title))
            kids = n.get('children', [])
            if kids:
                if not n.get('질문') or not n.get('선택지'):
                    ERRORS.append('비-리프에 질문/선택지 없음: %s' % n['id'])
                    continue
                if len(n['선택지']) != len(kids):
                    ERRORS.append('선택지 수 ≠ 자식 수: %s' % n['id'])
                if len(n['선택지']) > 3:
                    ERRORS.append('선택지 3개 초과(decideClarify CLARIFY_OPTION_MAX 위반): %s' % n['id'])
                kid_ids = {c['id'] for c in kids}
                for o in n['선택지']:
                    if o.get('next') not in kid_ids:
                        ERRORS.append('선택지 next가 자식이 아님: %s → %s' % (n['id'], o.get('next')))
                if n.get('추가확인'):
                    ERRORS.append('비-리프에 추가확인이 붙음: %s' % n['id'])
            else:
                if n.get('질문') or n.get('선택지'):
                    ERRORS.append('리프에 질문/선택지가 붙음: %s' % n['id'])
        _ = ids


