"""
"교육·훈련 의무" 표 빌더 겸 검증기 (H-32 확장 — 트리 아님, 표).

역할(초보자용):
  74법 raw 원문을 훑어 "누가(대상자) · 어떤 교육을(교육종류) · 얼마마다(주기) 받아야 하는가"를
  근거조문과 함께 표(JSON 행 배열)로 만든다. 사람이 손으로 인용문·주기 숫자를 타이핑하지 않는다 —
  아래 SPEC에는 "어느 법 몇 조에 이런 문구가 있다"만 적고, 인용문은 이 스크립트가 raw 파일을
  직접 열어 뽑아 온다. 주기·기한 문자열도 raw 원문에 실재하는지 다시 찾아 확인하고,
  없으면 그 자리에서 빌드를 실패시킨다(환각 0).

[연계]
  읽기: local_server/knowledge/legal/raw/**/{법률,시행령,시행규칙}.txt · 행정규칙/*.txt
        각 법 _meta.json(법령ID) · 행정규칙/_admrul.json(고시ID) · 별표/*.txt
        _dashboard/loop/audit12_groups.json + audit12_groups_run.json (74법 목록)
  쓰기: _dashboard/training_table.json
  설계: _dashboard/H32_training_table_design.md (스키마·스캔방법론·검증기준·유지보수 설계)

실행: python3 local_server/knowledge/legal/_dashboard/loop/build_training_table.py
"""
import json
import os
import re
import sys
from datetime import datetime, timedelta, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
DASH = os.path.dirname(HERE)
LEGAL = os.path.dirname(DASH)
RAW = os.path.join(LEGAL, 'raw')
OUT = os.path.join(DASH, 'training_table.json')
KST = timezone(timedelta(hours=9))

TIER_FILE = {'법률': '법률.txt', '시행령': '시행령.txt', '시행규칙': '시행규칙.txt'}
ADM = '행정규칙'
RE_ART = re.compile(r'^\[제(\d+)조(?:의(\d+))?\]\s*(.*)$')        # 법률계열(대괄호)
RE_ART_ADM = re.compile(r'^제(\d+)조(?:의(\d+))?\s*\(')            # 고시계열(무대괄호) — L-54
RE_TITLE_ADM = re.compile(r'^제\d+조(?:의\d+)?\s*\(([^)]*)\)')     # 고시계열 조문 제목만 추출
HANG = '①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳'
RE_HO = re.compile(r'(?<= )\d{1,2}\.\s')
# 문장 끝. 고시계열은 항 기호 앞 공백이 없어("…한다.② …") '다. '만 찾으면 문장이 안 끊긴다(L-54).
RE_SENT_END = re.compile(r'다\.(?=\s|[①-⑳]|<|$)')

ERRORS = []


def load_laws():
    """74법 목록 = audit12_groups.json(73) ∪ audit12_groups_run.json에만 있는 1법(자연유산법).
    근거: _dashboard/H29_design.md §2 · build_vessel_doc_tree.py와 같은 목록(L-74 재발 방지)."""
    def flat(p):
        g = json.load(open(p, encoding='utf-8'))
        return [it for k in sorted(g, key=int) for it in g[k]]
    base = flat(os.path.join(HERE, 'audit12_groups.json'))
    run = flat(os.path.join(HERE, 'audit12_groups_run.json'))
    slugs = {x['slug'] for x in base}
    return base + [x for x in run if x['slug'] not in slugs]


LAWS = load_laws()
BY_SLUG = {x['slug']: x for x in LAWS}


def split_articles(text):
    """법률계열 raw(`[제10조] 제목 …`)를 조 단위로 쪼갠다. 첫 등장만 채택(부칙 재등장 방지)."""
    out, cur, buf = {}, None, []
    for line in text.split('\n'):
        m = RE_ART.match(line.strip())
        if m:
            if cur and cur not in out:
                out[cur] = '\n'.join(buf)
            cur = '제%s조' % m.group(1) + ('의%s' % m.group(2) if m.group(2) else '')
            buf = [line.strip()]
        elif cur is not None:
            buf.append(line)
    if cur and cur not in out:
        out[cur] = '\n'.join(buf)
    return out


def split_articles_adm(text):
    """고시계열 raw(`제7조(제목) ①…`, 대괄호 없음)를 조 단위로 쪼갠다(L-54). 첫 등장만 채택."""
    out, cur, buf = {}, None, []
    for line in text.split('\n'):
        s = line.strip()
        m = RE_ART_ADM.match(s)
        if m:
            if cur and cur not in out:
                out[cur] = '\n'.join(buf)
            cur = '제%s조' % m.group(1) + ('의%s' % m.group(2) if m.group(2) else '')
            buf = [s]
        elif cur is not None:
            buf.append(line)
    if cur and cur not in out:
        out[cur] = '\n'.join(buf)
    return out


_cache = {}


def article_body(slug, tier, article, notice=None):
    """(법, 계층[, 고시명], 조) → 그 조의 raw 원문 전체. 없으면 None."""
    key = (slug, tier, notice)
    if key not in _cache:
        p = path_of(slug, tier, notice)
        if not os.path.exists(p):
            _cache[key] = {}
        else:
            text = open(p, encoding='utf-8', errors='replace').read()
            _cache[key] = split_articles_adm(text) if tier == ADM else split_articles(text)
    return _cache[key].get(article)


def path_of(slug, tier, notice=None):
    law = BY_SLUG[slug]
    if tier == ADM:
        return os.path.join(law['raw'], ADM, notice + '.txt')
    return os.path.join(law['raw'], TIER_FILE[tier])


def rel(slug, tier, notice=None):
    return os.path.relpath(path_of(slug, tier, notice), LEGAL)


def law_id(slug, tier):
    """_meta.json의 families.<계층>.법령ID — 법령명이 바뀌어도 추적이 끊기지 않게(H-29 11항·L-74)."""
    p = os.path.join(BY_SLUG[slug]['raw'], '_meta.json')
    if not os.path.exists(p):
        return None
    fam = json.load(open(p, encoding='utf-8')).get('families', {})
    return (fam.get(tier) or {}).get('법령ID')


_adm_meta = {}


def admrul_id(slug, notice):
    """행정규칙/_admrul.json 의 ID(일련번호). ★개정되면 바뀐다(L-73) — 설계 §7 참조."""
    p = os.path.join(BY_SLUG[slug]['raw'], ADM, '_admrul.json')
    if p not in _adm_meta:
        _adm_meta[p] = json.load(open(p, encoding='utf-8')) if os.path.exists(p) else {}
    flat = {re.sub(r'\s+', '', k): v for k, v in _adm_meta[p].items()}
    return (flat.get(re.sub(r'\s+', '', notice)) or {}).get('ID')


def quote_of(body, anchor, span=300):
    """anchor를 포함한 문장을 원문에서 뽑아 인용문으로 쓴다(사람이 타이핑하지 않는다).

    항 기호(①…)·호 번호("3. ")를 문장 시작점으로 보고, 문장 끝은 괄호가 닫힌 자리의 "다. "로 잡는다.
    괄호 처리를 하는 이유: 서류 파일럿에서 `"…말한다. 이하 같다)"` 때문에 인용문이 엉뚱한 자리에서
    잘린 사고가 실제로 5건 있었다(H32_vessel_doc_tree_design.md §6).
    고시계열은 항 기호 뒤 공백이 없는 경우가 많아 공백을 요구하지 않는다(L-54).
    @returns 원문 부분문자열(최대 500자) 또는 None"""
    flat = re.sub(r'\s+', ' ', body)
    i = flat.find(anchor)
    if i < 0:
        return None
    start = 0
    for mark in HANG:
        j = flat.rfind(mark, 0, i)
        if j > start:
            start = j
    j = flat.rfind('다. ', 0, i)
    while j >= 0:
        seg = flat[j + 3:i]
        if seg.count(')') <= seg.count('(') and seg.count('）') <= seg.count('（'):
            break
        j = flat.rfind('다. ', 0, j)
    if j >= 0 and j + 3 > start:
        start = j + 3
    for m in RE_HO.finditer(flat, 0, i):
        if m.start() > start:
            start = m.start()
    end = None
    for m in RE_SENT_END.finditer(flat, max(i, i + len(anchor) - 1)):
        seg = flat[start:m.start()]
        if seg.count('(') == seg.count(')') and seg.count('（') == seg.count('）'):
            end = m.end()
            break
    if end is None or end <= i:
        end = min(len(flat), i + span)
    return flat[start:end].strip()[:500]


# ── 스캔(커버리지 산출) — 설계 §1. 매 빌드마다 실제로 다시 돌린다 ─────────────
SCAN_EDU = re.compile(r'(교육|훈련|연수|강습)')
SCAN_OBL = re.compile(r'(받아야|받게 하여야|받도록 하여야|받도록 해야|이수하여야|이수해야|이수하도록'
                      r'|실시하여야|실시해야|실시하고|참여하여야|받아야 하며|이수한 사람|이수한 자|이수하지)')
SCAN_WIN = 90      # ★실측으로 정한 창 크기(설계 §1.1 — 120에서 늘어난 2건은 전부 오탐이었다)


def scan_corpus():
    """74법 raw 전체를 훑어 커버리지 수치를 만든다(갈래 A: 문장 근접 / 갈래 B: 조문 제목).
    @returns {files, articles, sentence_candidates, title_candidates, laws_with_candidates[]}"""
    files = arts = sent = title = 0
    hit = set()
    for law in LAWS:
        targets = [(os.path.join(law['raw'], f), False)
                   for f in sorted(os.listdir(law['raw'])) if f.endswith('.txt')]
        ad = os.path.join(law['raw'], ADM)
        if os.path.isdir(ad):
            targets += [(os.path.join(ad, f), True)
                        for f in sorted(os.listdir(ad)) if f.endswith('.txt')]
        for path, is_adm in targets:
            files += 1
            text = open(path, encoding='utf-8', errors='replace').read()
            d = split_articles_adm(text) if is_adm else split_articles(text)
            arts += len(d)
            for art, body in d.items():
                # 갈래 B — 조문 "제목"에만 교육 키워드가 있는가(본문은 보지 않는다).
                # 계열마다 제목이 있는 자리가 다르다(L-54): 법률계열은 `] ` 뒤, 고시계열은 괄호 안.
                head = body.split('\n')[0]
                if is_adm:
                    m = RE_TITLE_ADM.match(head)
                    tit = m.group(1) if m else ''
                else:
                    m = RE_ART.match(head)
                    tit = (m.group(3) or '').split('(')[0] if m else ''
                if SCAN_EDU.search(tit):
                    title += 1
                    hit.add(law['slug'])
                t = re.sub(r'\s+', ' ', body)
                for s in re.split(r'(?=[①-⑳])|(?<=한다\.)|(?<=된다\.)|(?<=아니한다\.)', t):
                    s = s.strip()
                    if not s or len(s) > 900:
                        continue
                    for mm in SCAN_OBL.finditer(s):
                        if SCAN_EDU.search(s[max(0, mm.start() - SCAN_WIN):mm.start()]):
                            sent += 1
                            hit.add(law['slug'])
                            break
    return {'files': files, 'articles': arts, 'sentence_candidates': sent,
            'title_candidates': title, 'laws_with_candidates': sorted(hit)}


# ── 행 생성 ───────────────────────────────────────────────────────────────
def eff(요지, slug, tier, article, anchor, notice=None, also=None):
    """미이수시효과 1건 — 벌칙·자격정지 등. ★근거조문의 앵커도 raw 대조한다(설계 §2.3-4).
    벌칙을 지어내는 것이 가장 위험하므로 별도 검증 대상으로 둔다."""
    body = article_body(slug, tier, article, notice)
    where = '%s %s %s' % (slug, notice or tier, article)
    if body is None:
        ERRORS.append('효과: 조문 없음: %s' % where)
        return None
    q = quote_of(body, anchor)
    if q is None:
        ERRORS.append('효과: 원문에 앵커 없음: %s ← "%s"' % (where, anchor))
        return None
    flat = re.sub(r'\s+', ' ', body)
    for a in (also or []):
        if a not in flat:
            ERRORS.append('효과: also 문구 없음: %s ← "%s"' % (where, a))
            return None
    e = {'요지': 요지, '근거법령': BY_SLUG[slug]['name'], '근거법령_slug': slug,
         '계층': tier, '근거조문': article, '파일': rel(slug, tier, notice), '인용': q}
    if tier == ADM:
        e['고시명'] = notice
    return e


def annex(slug, rel_path, quote):
    """별표참조 1건 — 주기·대상자·시간이 표에 있을 때(설계 §2.4).
    파일 실재 + 별표 제목 인용 실재를 확인한다. 표 칸은 줄바꿈으로 쪼개져 단일 문구 인용이
    어려우므로, 인용은 '무엇을 정한 별표인지'를 밝히는 제목 줄만 쓴다."""
    p = os.path.join(LEGAL, rel_path)
    if not os.path.exists(p):
        ERRORS.append('별표: 파일 없음: %s' % rel_path)
        return None
    txt = re.sub(r'\s+', ' ', open(p, encoding='utf-8', errors='replace').read())
    if re.sub(r'\s+', ' ', quote) not in txt:
        ERRORS.append('별표: 제목 인용이 파일에 없음: %s ← "%s"' % (rel_path, quote))
        return None
    return {'파일': rel_path, '인용': quote}


def row(대상자, 종류, slug, tier, article, anchor, notice=None, 주기=None, 기한=None,
        주기출처='조문본문', 주기근거=None, 효과=None, 별표=None, also=None, 주의=None):
    """표의 행 1건(설계 §2.2).

    anchor  = 인용문을 뽑을 자리이자 1차 검증 문구. 그 조문 원문에 없으면 빌드 실패.
    주기/기한 = ★원문 부분문자열이어야 한다(공백 정규화 후). 숫자를 요약하다 틀리면 곧바로
                오답이 되므로 빌더가 원문(또는 별표 파일)에서 다시 찾는다. 모르면 None.
    주기출처 = 조문본문 | 하위법령 | 별표(파일 확인) | 원문 미명시 (4값 고정 — 집계 가능하게)
    주기근거 = 주기출처가 '하위법령'일 때 어느 조문을 봐야 하는지(자유 문자열).
    also    = 여러 값을 묶어 적은 경우, 개별 문구가 실제로 같은 조문에 있는지 추가 검증.
    @returns 행 dict 또는 None(오류는 ERRORS에 적재 → 빌드 실패)
    [연계] 설계 §2.2 스키마 · §2.3 불변식 · §5 성공기준."""
    body = article_body(slug, tier, article, notice)
    where = '%s %s %s' % (slug, notice or tier, article)
    if body is None:
        ERRORS.append('행: 조문 없음: %s' % where)
        return None
    q = quote_of(body, anchor)
    if q is None:
        ERRORS.append('행: 원문에 앵커 없음: %s ← "%s"' % (where, anchor))
        return None
    if anchor not in re.sub(r'\s+', ' ', q):
        ERRORS.append('행: 인용문에 앵커가 안 담김(문장 경계 탐지 실패): %s ← "%s"' % (where, anchor))
        return None
    flat = re.sub(r'\s+', ' ', body)
    for a in (also or []):
        if a not in flat:
            ERRORS.append('행: also 문구 없음: %s ← "%s"' % (where, a))
            return None
    # ★주기·기한은 조문 본문 또는 지정한 별표 파일의 부분문자열이어야 한다
    haystack = flat
    if 별표:
        p = os.path.join(LEGAL, 별표['파일'])
        if os.path.exists(p):
            haystack += ' ' + re.sub(r'\s+', ' ', open(p, encoding='utf-8', errors='replace').read())
    for label, val in (('실시주기', 주기), ('이수기한', 기한)):
        if val is not None and re.sub(r'\s+', ' ', val) not in haystack:
            ERRORS.append('행: %s가 원문에 없음: %s ← "%s"' % (label, where, val))
            return None
    if 주기출처 not in ('조문본문', '하위법령', '별표(파일 확인)', '원문 미명시'):
        ERRORS.append('행: 주기출처 값이 규약 밖임: %s ← "%s"' % (where, 주기출처))
        return None
    if 주기출처 == '하위법령' and not 주기근거:
        ERRORS.append('행: 주기출처=하위법령인데 주기근거가 없음: %s' % where)
        return None
    if 주기 is None and 기한 is None and 주기출처 == '조문본문':
        ERRORS.append('행: 주기·기한이 모두 없는데 주기출처가 조문본문임: %s' % where)
        return None
    r = {
        '대상자유형': 대상자, '교육종류': 종류,
        '실시주기': 주기, '이수기한': 기한, '주기출처': 주기출처, '주기근거': 주기근거,
        '근거법령': BY_SLUG[slug]['name'], '근거법령_slug': slug,
        '계층': tier, '근거조문': article, '법령ID': law_id(slug, tier),
        '파일': rel(slug, tier, notice), '인용': q,
    }
    if tier == ADM:
        r['고시명'] = notice
        r['고시ID'] = admrul_id(slug, notice)
    if 효과:
        r['미이수시효과'] = 효과
    if 별표:
        r['별표참조'] = 별표
    if 주의:
        r['주의'] = 주의
    return r


