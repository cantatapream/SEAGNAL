def validate(rows):
    """§5 성공기준 — 행 단위 구조 검사(개별 raw 대조는 row()/eff()/annex()가 이미 수행)."""
    for r in rows:
        for k in ('대상자유형', '교육종류', '근거법령', '계층', '근거조문', '파일', '인용', '주기출처'):
            if not r.get(k):
                ERRORS.append('필수 필드 없음(%s): %s %s' % (k, r.get('근거법령'), r.get('근거조문')))
        if r['주기출처'] == '조문본문' and r.get('실시주기') is None and r.get('이수기한') is None:
            ERRORS.append('주기출처=조문본문인데 주기·기한이 모두 없음: %s %s'
                          % (r['근거법령'], r['근거조문']))
        if r['주기출처'] == '별표(파일 확인)' and not r.get('별표참조'):
            ERRORS.append('주기출처=별표인데 별표참조가 없음: %s %s' % (r['근거법령'], r['근거조문']))
        if r['계층'] == ADM and not r.get('고시명'):
            ERRORS.append('행정규칙인데 고시명 없음: %s %s' % (r['근거법령'], r['근거조문']))


