def validate():
    """조인 무결성·필수 필드·정직성 규칙 검사(설계 §5-5). 위반은 ERRORS에 적재."""
    cert_ids = {c['id'] for c in CERTS}
    for it in INSPECTIONS:
        if it['증서id'] and it['증서id'] not in cert_ids:
            ERRORS.append('증서id 참조 깨짐: %s → %s' % (it['id'], it['증서id']))
        if it['대상_트리노드'] and TREE_NODES and it['대상_트리노드'] not in TREE_NODES:
            ERRORS.append('트리노드 없음: %s → %s' % (it['id'], it['대상_트리노드']))
        for v in it['시기'] + it['연기'] + it['면제']:
            if v['문구'] is None and v['출처'] == '조문본문':
                ERRORS.append('문구 없이 출처를 조문본문으로 둠: %s' % it['id'])
    ids = [x['id'] for x in INSPECTIONS]
    if len(ids) != len(set(ids)):
        ERRORS.append('검사종류 id 중복: %s' % [i for i in ids if ids.count(i) > 1])
    cids = [c['id'] for c in CERTS]
    if len(cids) != len(set(cids)):
        ERRORS.append('증서 id 중복: %s' % [i for i in cids if cids.count(i) > 1])
    for c in CERTS:
        if not c['유효기간']:
            ERRORS.append('유효기간 없는 증서(넣지 말 것): %s' % c['id'])
        if c['연장']['가능'] is None and not c['연장']['주의']:
            ERRORS.append('연장 미확인인데 사유 메모가 없음: %s' % c['id'])


def independent_recheck():
    """★독립 재대조(설계 §6) — 빌더의 조문분리 로직을 재사용하지 않는다.

    파일을 통짜 문자열로 읽어 ①인용문 ②기간 문구가 실재하는지, ③인용문이 정말 그
    조문 범위 안에서 나오는지를 문자열 검색만으로 다시 확인한다.
    @returns 검사한 블록 수 (실패는 ERRORS에 적재)"""
    raw_cache = {}

    def whole(path):
        if path not in raw_cache:
            raw_cache[path] = re.sub(
                r'\s+', ' ', open(os.path.join(LEGAL, path), encoding='utf-8', errors='replace').read())
        return raw_cache[path]

    def span_of(flat, key):
        """[제N조] 마커의 첫 출현부터 다음 [제 마커까지 — 빌더의 split_articles와 독립."""
        i = flat.find('[%s]' % key)
        if i < 0:
            return None
        j = flat.find('[제', i + 1)
        return flat[i:(j if j > 0 else len(flat))]

    n = 0
    def check(ev_, 문구=None, who=''):
        nonlocal n
        if not ev_:
            return
        n += 1
        path = os.path.join(LEGAL, ev_['파일'])
        if not os.path.exists(path):
            ERRORS.append('[독립재대조] 파일 없음: %s (%s)' % (ev_['파일'], who))
            return
        flat = whole(ev_['파일'])
        if ev_['인용'] not in flat:
            ERRORS.append('[독립재대조] 인용문이 파일에 없음: %s %s (%s)' % (ev_['법령'], ev_['조문'], who))
            return
        sp = span_of(flat, ev_['조문키'])
        if sp is None:
            ERRORS.append('[독립재대조] 조문 마커 없음: %s %s' % (ev_['법령'], ev_['조문키']))
        elif ev_['인용'] not in sp:
            ERRORS.append('[독립재대조] 인용문이 그 조문 범위 밖: %s %s (%s)' % (ev_['법령'], ev_['조문'], who))
        if 문구 is not None and 문구 not in flat:
            ERRORS.append('[독립재대조] 기간 문구가 파일에 없음: %s %s ← "%s"' % (ev_['법령'], ev_['조문'], 문구))

    for it in INSPECTIONS:
        check(it['근거'], who=it['id'])
        for v in it['시기'] + it['연기'] + it['면제']:
            check(v['근거'], v['문구'], it['id'])
    for c in CERTS:
        check(c['발급근거'], who=c['id'])
        for v in c['유효기간'] + c['기산'] + c['효력정지'] + c['연장']['사유']:
            check(v['근거'], v['문구'], c['id'])
        if c['연장']['상한']:
            check(c['연장']['상한']['근거'], c['연장']['상한']['문구'], c['id'])
    return n


