# 74법 전수 스캔(커버리지 산출용) — 표 내용을 만들지는 않고 "어디까지 훑었는지"만 남긴다.
#   설계 §3.2의 3단계 정규식을 각각 따로 센다(어느 표현이 몇 법을 데려왔는지 추적 가능하게).
# ═══════════════════════════════════════════════════════════════════
SCAN_1 = re.compile(r'정기검사|중간검사|임시검사|특별검사|건조검사')          # 지시 정규식 원문
SCAN_2 = re.compile(r'인증심사|보안심사|인증검사|안전검사|안전성 검사'
                    r'|예항력검사|임시항해검사|임시항행검사|국제협약검사|강화검사')
SCAN_3 = re.compile(r'검사[^.]{0,80}유효기간|유효기간[^.]{0,80}검사')


def scan_corpus():
    """74법 raw 전체(법률계열 + 행정규칙계열)를 훑어 커버리지 수치를 만든다.
    @returns {files, articles, laws, hit_1/2/3(법 slug 목록), hit_any}
    [연계] 설계 §5-1 커버리지 공개 · L-54(계열별 이중 형식)."""
    files = articles = 0
    hit = {1: set(), 2: set(), 3: set()}
    for law in LAWS:
        targets = [(os.path.join(law['raw'], f), True)
                   for f in sorted(os.listdir(law['raw'])) if f.endswith('.txt')]
        ad = os.path.join(law['raw'], '행정규칙')
        if os.path.isdir(ad):
            targets += [(os.path.join(ad, f), False)
                        for f in sorted(os.listdir(ad)) if f.endswith('.txt')]
        for path, bracket in targets:
            files += 1
            text = open(path, encoding='utf-8', errors='replace').read()
            if bracket:
                arts = list(split_articles(text).items())
            else:
                arts, cur, buf = [], None, []
                for line in text.split('\n'):
                    m = RE_ART_NB.match(line.strip())
                    if m:
                        if cur:
                            arts.append((cur, '\n'.join(buf)))
                        cur, buf = m.group(0), [line.strip()]
                    elif cur is not None:
                        buf.append(line)
                if cur:
                    arts.append((cur, '\n'.join(buf)))
            articles += len(arts)
            for _, body in arts:
                t = re.sub(r'\s+', ' ', body)
                for n, pat in ((1, SCAN_1), (2, SCAN_2), (3, SCAN_3)):
                    if pat.search(t):
                        hit[n].add(law['slug'])
    return {'laws': len(LAWS), 'files': files, 'articles': articles,
            'hit_지시정규식': sorted(hit[1]), 'hit_심사안전검사계열': sorted(hit[2]),
            'hit_검사x유효기간': sorted(hit[3]),
            'hit_any': sorted(hit[1] | hit[2] | hit[3])}


