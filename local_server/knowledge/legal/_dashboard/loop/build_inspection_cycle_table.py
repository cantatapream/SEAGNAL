def split_articles(text):
    """법률계열 raw(`[제10조] 제목 …`)를 조 단위로 쪼갠다.
    ※ 고시계열은 마커 형식이 달라(L-54) 이 함수로 못 읽는다 — SPEC은 법률계열만 쓴다.
    @returns {'제16조': '조문 원문 …', …}"""
    out, cur, buf = {}, None, []
    for line in text.split('\n'):
        m = RE_ART.match(line.strip())
        if m:
            if cur and cur not in out:
                out[cur] = '\n'.join(buf)
            cur = '제%s조' % m.group(1) + ('의%s' % m.group(2) if m.group(2) else '')
            buf = [line.strip()]
        else:
            if cur is not None:
                buf.append(line)
    if cur and cur not in out:
        out[cur] = '\n'.join(buf)
    return out


_cache = {}


def article_body(slug, tier, article):
    """(법, 계층, 조) → 그 조의 raw 원문 전체. 없으면 None."""
    key = (slug, tier)
    if key not in _cache:
        law = BY_SLUG.get(slug)
        if not law:
            _cache[key] = {}
        else:
            p = os.path.join(law['raw'], TIER_FILE[tier])
            _cache[key] = split_articles(open(p, encoding='utf-8', errors='replace').read()) \
                if os.path.exists(p) else {}
    return _cache[key].get(article)


def law_id(slug, tier):
    """_meta.json의 families.<계층>.법령ID — 법령명이 바뀌어도 추적이 끊기지 않게(H-29 11항·L-74)."""
    law = BY_SLUG.get(slug)
    if not law:
        return None
    p = os.path.join(law['raw'], '_meta.json')
    if not os.path.exists(p):
        return None
    fam = json.load(open(p, encoding='utf-8')).get('families', {})
    return (fam.get(tier) or {}).get('법령ID')


def rel(slug, tier):
    return os.path.relpath(os.path.join(BY_SLUG[slug]['raw'], TIER_FILE[tier]), LEGAL)


HANG = '①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳'


MAXQ = 700     # 인용문 길이 상한. 이보다 길면 앵커 주변으로 좁힌다(잘라서 앵커를 잃지 않게).


def quote_of(body, anchor, span=240):
    """anchor를 포함한 문장을 원문에서 뽑아 인용문으로 쓴다(사람이 타이핑하지 않는다).

    ① 항 기호(①…)가 앞에 있으면 그 자리를 문장 시작으로 본다(괄호 안 "…말한다. 이하 같다)"
       때문에 문장이 중간부터 잘리는 것을 막는다).
    ② 그러나 표·각 호 나열처럼 한 항이 아주 긴 경우가 있어(선박안전법 시행규칙 제19조제2항의
       중간검사 시기 표), 그대로 두면 인용문이 상한에 잘려 정작 앵커를 안 담는다. 그럴 때는
       앵커 앞쪽 가까운 경계(마침표·표 구분선·호 번호)로 시작점을 당긴다.
    ③ 끝점은 반드시 앵커 뒤에서 찾는다 — 앵커 안에 "…말한다. " 가 들어 있으면 앵커 중간에서
       잘려 검증(§5-4)이 실패하기 때문이다.
    @returns 원문 부분문자열 또는 None(앵커가 원문에 없을 때)
    [연계] ev()가 이 결과를 인용문으로 쓰고, 앵커 포함 여부를 다시 검사한다."""
    flat = re.sub(r'\s+', ' ', body)
    i = flat.find(anchor)
    if i < 0:
        return None
    start = -1
    for mark in HANG:
        j = flat.rfind(mark, 0, i)
        if j > start:
            start = j
    if start < 0:
        start = max(0, flat.rfind('. ', 0, i) + 1)
    if i - start > MAXQ // 2:                      # ② 항이 너무 길다 → 가까운 경계로 당긴다
        near = max((flat.rfind(s, max(0, i - MAXQ // 2), i) for s in ('. ', '│', '┼', '  ')),
                   default=-1)
        start = (near + 1) if near > 0 else max(0, i - 120)
    j = i + len(anchor)
    end = flat.find('다. ', j)                      # ③ 끝점은 앵커 뒤에서
    end = (end + 2) if end > 0 else min(len(flat), j + span)
    q = flat[start:end].strip()
    if len(q) > MAXQ:                              # 앵커를 반드시 남기며 줄인다
        q = flat[max(start, i - 120):min(end, j + 200)].strip()
    return q


def ev(slug, tier, art, anchor, disp=None):
    """근거 1건 = {법령·계층·조문·법령ID·파일·인용}. 앵커가 raw에 없으면 빌드 실패.

    예: ev('선박안전법', '법률', '제16조', '5개월 이내의 범위에서', '제16조제2항')
    @param art   조문키(조 단위, split_articles의 키). 예 '제16조'·'제16조의2'
    @param disp  사람에게 보일 조문 표기(항·호까지). 없으면 art 그대로.
    @returns dict 또는 None(실패 시 ERRORS에 사유 적재)
    [연계] 설계 §2.3 '값+근거' 블록의 근거 부분 · §5-2 전량 재대조."""
    body = article_body(slug, tier, art)
    where = '%s %s %s' % (slug, tier, art)
    if body is None:
        ERRORS.append('조문 없음: %s' % where)
        return None
    q = quote_of(body, anchor)
    if q is None:
        ERRORS.append('원문에 앵커 없음: %s ← "%s"' % (where, anchor))
        return None
    if anchor not in re.sub(r'\s+', ' ', q):
        # 인용문이 길이 상한에 잘려 정작 앵커를 안 담은 경우(설계 §5-4).
        ERRORS.append('인용문에 앵커가 안 담김: %s ← "%s"' % (where, anchor))
        return None
    return {'법령': BY_SLUG[slug]['name'], '법령_slug': slug, '계층': tier,
            '조문': disp or art, '조문키': art, '법령ID': law_id(slug, tier),
            '파일': rel(slug, tier), '인용': q}


def val(text, slug=None, tier=None, art=None, anchor=None, src='조문본문', 구분=None):
    """기간·수치 값 1건(설계 §2.3).

    text  = 기간 문구. ★raw 원문의 부분문자열이어야 통과 — 숫자를 요약·의역하면 빌드 실패.
            모르면 None(지어내지 않는다). 이때 src로 왜 모르는지를 남긴다.
    src   = 조문본문 | 조문본문 표(이미지판독·⚠REVIEW) | 하위법령(raw 미수집)
    @returns {'구분','문구','출처','근거'}
    [연계] 설계 §2.3 불변식 · §4 기간표현 표 · §5-3 원문 일치 강제."""
    e = {'구분': 구분, '문구': text, '출처': src, '근거': None}
    if slug is None:
        return e
    e['근거'] = ev(slug, tier, art, anchor if anchor is not None else text)
    if text is not None and e['근거'] is not None:
        flat = re.sub(r'\s+', ' ', article_body(slug, tier, art))
        if text not in flat:
            ERRORS.append('기간 문구가 원문에 없음: %s %s %s ← "%s"' % (slug, tier, art, text))
            return None
    return e


TREE_NODES = set()


def load_tree_nodes():
    """vessel_doc_tree.json의 노드 id를 모은다(읽기만 — 그 파일은 수정하지 않는다).
    '대상_트리노드'가 실재 노드인지 검사하는 데만 쓴다(설계 §9-5: 조인 키가 아니라 힌트)."""
    if not os.path.exists(TREE):
        return
    def walk(n):
        TREE_NODES.add(n['id'])
        for c in n.get('children', []):
            walk(c)
    walk(json.load(open(TREE, encoding='utf-8'))['tree'])


