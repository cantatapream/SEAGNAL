def split_articles(text):
    """법률계열 raw(`[제10조] 제목 …`)를 조 단위로 쪼갠다.
    @returns {'제22조': '조문 원문 …', …}
    ※ 고시계열은 마커 형식이 달라(L-54) split_articles_admrul()을 따로 쓴다."""
    out, cur, buf = {}, None, []
    for line in text.split('\n'):
        s = line.strip()
        m = RE_ART.match(s)
        if m:
            if cur:
                out[cur] = '\n'.join(buf)
            cur = '제%s조' % m.group(1) + ('의%s' % m.group(2) if m.group(2) else '')
            buf = [s]
        elif RE_CHAP.match(s):
            continue        # 편/장/절 제목 줄은 조문 본문이 아니다 — 인용문 끝에 딸려 붙는 것을 막는다
        else:
            if cur is not None:
                buf.append(line)
    if cur:
        out[cur] = '\n'.join(buf)
    return out


def split_articles_admrul(text):
    """고시계열 raw(`제7조(제목) ①…`, 대괄호 없음)를 조 단위로 쪼갠다(L-54).
    ★첫 등장만 채택 — 본문 뒤에 표 전사 부록이 붙어 같은 조 마커가 다시 걸리는 파일이 있다."""
    out, cur, buf = {}, None, []
    for line in text.split('\n'):
        s = line.strip()
        m = RE_ART_NB.match(s)
        if m:
            if cur and cur not in out:
                out[cur] = '\n'.join(buf)
            cur = '제%s조' % m.group(1) + ('의%s' % m.group(2) if m.group(2) else '')
            buf = [s]
        else:
            if cur is not None:
                buf.append(line)
    if cur and cur not in out:
        out[cur] = '\n'.join(buf)
    return out


_cache = {}


def tier_path(slug, tier):
    """(법, 계층) → raw txt 절대경로. 계층='별표'는 annex_path()가 따로 맡는다."""
    return os.path.join(BY_SLUG[slug]['raw'], TIER_FILE[tier])


def annex_path(slug, annex):
    """(법, '별표2') → 별표 txt 절대경로. 별표는 조문 마커가 없어 파일 전체가 한 단위다."""
    return os.path.join(BY_SLUG[slug]['raw'], '별표', annex + '.txt')


def article_body(slug, tier, article):
    """(법, 계층, 조) → 그 조의 raw 원문 전체. 없으면 None.
    계층='별표'면 article이 별표 이름('별표2')이고 파일 전체를 돌려준다."""
    if tier == '별표':
        p = annex_path(slug, article)
        return open(p, encoding='utf-8', errors='replace').read() if os.path.exists(p) else None
    key = (slug, tier)
    if key not in _cache:
        p = tier_path(slug, tier)
        _cache[key] = split_articles(open(p, encoding='utf-8', errors='replace').read()) \
            if os.path.exists(p) else {}
    return _cache[key].get(article)


def law_id(slug, tier):
    """_meta.json의 families.<계층>.법령ID — 법령명이 바뀌어도 추적이 끊기지 않게(H-29 11항·L-74)."""
    p = os.path.join(BY_SLUG[slug]['raw'], '_meta.json')
    if not os.path.exists(p):
        return None
    fam = json.load(open(p, encoding='utf-8')).get('families', {})
    return (fam.get(TIER_META.get(tier, tier)) or {}).get('법령ID')


def rel(slug, tier, article=None):
    p = annex_path(slug, article) if tier == '별표' else tier_path(slug, tier)
    return os.path.relpath(p, LEGAL)


HANG = '①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳'
RE_HO = re.compile(r'(?<= )\d{1,2}\. ')        # 호 번호 " 1. " (raw "   1.  본문" → 정규화하면 " 1. ")
RE_MOK = re.compile(r'(?<= )[가-힣]\. ')       # 목 기호 " 가. " — 앞 공백이 조건이라 "…한다. "와 구별된다


def _markers(flat, lo, hi):
    """[lo,hi) 구간에 있는 구조 표지(항 기호·호 번호·목 기호)의 위치를 모두 돌려준다."""
    pos = []
    for mark in HANG:
        j = flat.find(mark, lo, hi)
        while j >= 0:
            pos.append(j)
            j = flat.find(mark, j + 1, hi)
    for rx in (RE_HO, RE_MOK):
        for m in rx.finditer(flat[lo:hi]):
            pos.append(lo + m.start())
    return pos


def quote_of(body, anchor, span=220):
    """anchor를 포함한 **그 항·호·목 하나**를 원문에서 뽑아 인용문으로 쓴다(사람이 타이핑하지 않는다).

    경계 잡는 법 — 조문은 항(①)·호(1.)·목(가.)이라는 구조 표지로 쪼개져 있으므로
    **앞쪽은 직전 표지, 뒤쪽은 다음 표지**를 경계로 삼는다. 양쪽을 다 막지 않으면
    "…배출할 것 2. 다음 각 목의 구분에 따라 기름을…"처럼 **옆 호까지 끌고 오는 인용**이 나온다.
    표지가 하나도 없는 조문(단문 조문)일 때만 문장 끝("다. ")으로 자른다.
    ※ 이 raw는 항 기호 뒤에 공백이 없는 경우가 많아(`①누구든지`) 기호 문자 자체로 찾는다(L-54 계열).
    @param body 조문 원문 · @param anchor 그 안에 있어야 할 문구
    @returns 원문 부분문자열(최대 400자) 또는 None(anchor가 없을 때)
    [연계] rule()·prov()가 이 결과를 `인용`으로 싣고, verify()가 raw에서 다시 대조한다."""
    flat = re.sub(r'\s+', ' ', body)
    i = flat.find(anchor)
    if i < 0:
        return None
    befores = _markers(flat, 0, i)
    # 표지가 하나도 없으면(항·호가 없는 단문 조문) 조문 첫머리부터 인용한다 —
    # 문장 끝("다. ")으로 자르면 "…말한다. 이하 같다)는 관할수역에서…"처럼 주어가 잘린다.
    start = max(befores) if befores else 0

    tail = i + len(anchor)
    afters = _markers(flat, tail, len(flat))
    j = flat.find('다. ', tail)
    if j >= 0:
        afters.append(j + 2)
    end = min(afters) if afters else min(len(flat), i + span)
    return flat[start:end].strip()[:400]


ERRORS = []

# ── 74법 전수 스캔(커버리지 산출용) ────────────────────────────────
# 설계 §5.2 — 물질어 × 규제어가 같은 문장에 있으면 후보로 센다.
# 트리 내용을 만들지는 않는다. "어디까지 훑었는지"를 수치로 남기려고 매 빌드마다 다시 돌린다.
SCAN_MAT = re.compile(r'(폐기물|분뇨|기름|유류|선저폐수|유해액체물질|포장유해물질|대기오염물질'
                      r'|오존층파괴물질|질소산화물|황산화물|황함유량|휘발성유기화합물|선박평형수'
                      r'|방오도료|방오시스템)')
SCAN_REG = re.compile(r'(배출하여서는 아니|배출해서는 아니|배출하여서는 안|배출기준|배출허용기준'
                      r'|처리기준|버려서는 아니|투기하여서는|배출할 수 없|사용하여서는 아니'
                      r'|배출규제|누출ㆍ유출|유출하거나|배출률|배출을 금지)')


def scan_corpus():
    """74법 raw 전체(법률계열 + 행정규칙계열)를 훑어 커버리지 수치를 만든다.
    @returns {files, articles, candidates, laws_with_candidates:[slug…]}
    [연계] 설계 §5.2·§6 성공기준 1번(정확도가 아니라 '어디까지 봤는지'를 밝히는 수치)."""
    files = articles = cands = 0
    hit = set()
    for law in LAWS:
        targets = [(os.path.join(law['raw'], f), True)
                   for f in sorted(os.listdir(law['raw'])) if f.endswith('.txt')]
        ad = os.path.join(law['raw'], '행정규칙')
        if os.path.isdir(ad):
            targets += [(os.path.join(ad, f), False)
                        for f in sorted(os.listdir(ad)) if f.endswith('.txt')]
        for path, bracket in targets:
            files += 1
            text = open(path, encoding='utf-8', errors='replace').read()
            arts = split_articles(text) if bracket else split_articles_admrul(text)
            articles += len(arts)
            for _, body in arts.items():
                t = re.sub(r'\s+', ' ', body)
                for s in re.split(r'(?=[①-⑳])|(?<=한다\.)|(?<=된다\.)|(?<=아니한다\.)', t):
                    s = s.strip()
                    if not s or len(s) > 700:
                        continue
                    if SCAN_MAT.search(s) and SCAN_REG.search(s):
                        cands += 1
                        hit.add(law['slug'])
                        break
    return {'files': files, 'articles': articles, 'candidates': cands,
            'laws_with_candidates': sorted(hit)}   # candidates = 후보가 나온 '조문' 수(문장 수 아님)


def scan_mepr():
    """설계 §5.3의 부령 1건을 따로 센다 — 74법 수치와 섞지 않는다(범위를 정직하게 분리)."""
    p = tier_path(MEPR_SLUG, '규칙')
    arts = split_articles(open(p, encoding='utf-8', errors='replace').read())
    ann = os.path.join(MEPR['raw'], '별표')
    n_ann = len([f for f in os.listdir(ann) if f.endswith('.txt')]) if os.path.isdir(ann) else 0
    return {'files': 1, 'articles': len(arts), 'annex_files': n_ann}


