def rule(요건, 유형, slug, tier, article, anchor, cond=None, excl=None,
         deleg=None, note=None, also=None, src=None):
    """규제 항목 1건(설계 §2.3).

    유형   = 금지행위 | 배출기준 | 처리의무 | 적용제외 (설계 §2.4)
    anchor = 인용문을 뽑을 자리이자 1차 검증 문구. 그 조문 원문에 없으면 빌드 실패.
    also   = 하나의 항목이 여러 요건을 묶은 경우, 개별 문구가 실제로 같은 조문에 있는지
             추가 검증하는 문구들(인용문에 안 담겨도 검증은 통과해야 한다).
    src    = 수치의 출처를 밝혀야 할 때('별표(raw 미수집)' 등) — 없으면 필드를 안 만든다.
    @returns 규제 항목 dict 또는 None(오류는 ERRORS에 쌓이고 main이 빌드를 중단시킨다)
    [연계] validate()가 유형·필수필드를 검사하고, verify()가 raw에서 다시 대조한다."""
    body = article_body(slug, tier, article)
    where = '%s %s %s' % (slug, tier, article)
    if body is None:
        ERRORS.append('규제: 조문 없음: %s' % where)
        return None
    q = quote_of(body, anchor)
    if q is None:
        ERRORS.append('규제: 원문에 앵커 없음: %s ← "%s"' % (where, anchor))
        return None
    if anchor not in re.sub(r'\s+', ' ', q):
        # 인용문이 400자 상한에 잘려 정작 anchor를 안 담은 경우 — 조용히 넘기면 엉뚱한 인용이 된다.
        ERRORS.append('규제: 인용문에 앵커가 안 담김(문장 경계 탐지 실패): %s ← "%s"' % (where, anchor))
        return None
    flat = re.sub(r'\s+', ' ', body)
    for a in (also or []):
        if a not in flat:
            ERRORS.append('규제: also 문구 없음: %s ← "%s"' % (where, a))
            return None
    e = {
        '요건': 요건, '요건유형': 유형,
        '근거법령': BY_SLUG[slug]['name'], '근거법령_slug': slug,
        '계층': tier, '근거조문': article, '법령ID': law_id(slug, tier),
        '파일': rel(slug, tier, article), '인용': q, '조건': cond,
    }
    if excl:
        e['적용제외'] = excl
    if deleg:
        e['위임'] = deleg
    if src:
        e['수치출처'] = src
    if note:
        e['주의'] = note
    return e


def prov(slug, tier, article, anchor, disp=None):
    """노드 출처 1건 — 출처 없는 노드는 만들지 않는다(설계 §3.1)."""
    body = article_body(slug, tier, article)
    if body is None:
        ERRORS.append('provenance 조문 없음: %s %s %s' % (slug, tier, article))
        return None
    q = quote_of(body, anchor)
    if q is None:
        ERRORS.append('provenance 앵커 없음: %s %s %s ← "%s"' % (slug, tier, article, anchor))
        return None
    return {'법령': BY_SLUG[slug]['name'], '법령_slug': slug, '계층': tier,
            '조문': disp or article, '법령ID': law_id(slug, tier),
            '파일': rel(slug, tier, article), '인용': q}


