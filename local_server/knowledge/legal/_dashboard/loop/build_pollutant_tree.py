KINDS = ('금지행위', '배출기준', '처리의무', '적용제외')


def walk(n):
    yield n
    for c in n.get('children', []):
        for x in walk(c):
            yield x


def validate(root):
    """설계 §6의 성공기준 2·3을 빌드 시점에 강제한다. 위반은 ERRORS에 쌓여 빌드를 중단시킨다."""
    ids = set()
    for n in walk(root):
        if n['id'] in ids:
            ERRORS.append('중복 id: %s' % n['id'])
        ids.add(n['id'])
        if not n.get('provenance') or any(p is None for p in n['provenance']):
            ERRORS.append('노드 출처 없음/빌드 실패: %s' % n['id'])
        if any(r is None for r in n.get('규제', [])):
            ERRORS.append('규제 항목 빌드 실패 포함: %s' % n['id'])
        for r in n.get('규제', []):
            if r and r['요건유형'] not in KINDS:
                ERRORS.append('알 수 없는 요건유형: %s ← %s' % (n['id'], r['요건유형']))
        kids = n.get('children', [])
        if kids:
            if not n.get('질문') or not n.get('선택지'):
                ERRORS.append('비-리프에 질문/선택지 없음: %s' % n['id'])
                continue
            if len(n['선택지']) != len(kids):
                ERRORS.append('선택지 수 ≠ 자식 수: %s' % n['id'])
            if len(n['선택지']) > 3:
                ERRORS.append('선택지 3개 초과(decideClarify CLARIFY_OPTION_MAX 위반): %s' % n['id'])
            kid_ids = {c['id'] for c in kids}
            for o in n['선택지']:
                if o.get('next') not in kid_ids:
                    ERRORS.append('선택지 next가 자식이 아님: %s → %s' % (n['id'], o.get('next')))
            if n.get('추가확인'):
                ERRORS.append('비-리프에 추가확인이 붙음: %s' % n['id'])
        else:
            if n.get('질문') or n.get('선택지'):
                ERRORS.append('리프에 질문/선택지가 붙음: %s' % n['id'])


# ── 독립 재대조(설계 §6-4) ─────────────────────────────────────────
# ★위쪽 빌더 함수(split_articles·article_body·quote_of)를 일부러 하나도 쓰지 않는다.
#   같은 로직으로 만들고 같은 로직으로 검사하면 로직의 버그를 검사가 통과시킨다.
RE_ANY_ART = re.compile(r'\[제\d+조(?:의\d+)?\]')


def verify(path=OUT):
    """산출된 JSON을 다시 열어, 파일을 통짜 문자열로 읽어 인용문이 실재하는지 대조한다.
    검사 3가지: ①파일 존재 ②인용문이 파일 안에 부분문자열로 실재 ③그 인용이 정말 그 조문 범위 안.
    @returns 실패 목록(빈 리스트면 통과)"""
    d = json.load(open(path, encoding='utf-8'))
    fails, checked = [], 0

    def norm(s):
        return re.sub(r'\s+', ' ', s)

    def span_of(text, article):
        """조문 경계를 문자열 검색으로 따로 구한다(빌더의 조 분리 로직과 무관하게)."""
        i = text.find('[%s]' % article)
        if i < 0:
            return None
        m = RE_ANY_ART.search(text, i + 1)
        return text[i:m.start() if m else len(text)]

    def check(kind, ident, item, quote_key='인용'):
        nonlocal checked
        checked += 1
        p = os.path.join(LEGAL, item['파일'])
        if not os.path.exists(p):
            fails.append('%s %s: 파일 없음 %s' % (kind, ident, item['파일']))
            return
        raw = open(p, encoding='utf-8', errors='replace').read()
        q = norm(item[quote_key])
        if q not in norm(raw):
            fails.append('%s %s: 인용문이 파일에 없음 (%s)' % (kind, ident, item['파일']))
            return
        art = item.get('근거조문') or item.get('조문')
        tier = item.get('계층')
        if tier != '별표' and art and art.startswith('제'):
            base = re.match(r'제\d+조(?:의\d+)?', art).group(0)
            body = span_of(raw, base)
            if body is None:
                fails.append('%s %s: 조문 %s를 파일에서 못 찾음' % (kind, ident, base))
            elif q not in norm(body):
                fails.append('%s %s: 인용문이 %s 범위 밖에서 나옴' % (kind, ident, base))

    for n in walk(d['tree']):
        for p in n.get('provenance', []) + n.get('구분근거', []):
            check('노드출처', '%s/%s %s' % (n['id'], p['법령'], p['조문']), p)
        for r in n.get('규제', []):
            check('규제', '%s/%s %s' % (n['id'], r['근거법령'], r['근거조문']), r)
    return fails, checked


