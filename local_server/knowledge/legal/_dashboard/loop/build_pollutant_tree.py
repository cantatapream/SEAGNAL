RE_ART = re.compile(r'^\[제(\d+)조(?:의(\d+))?\]\s*(.*)$')      # 법률계열(대괄호)
RE_ART_NB = re.compile(r'^제(\d+)조(?:의(\d+))?\s*\(([^)]*)\)')  # 고시계열(무대괄호, L-54)
